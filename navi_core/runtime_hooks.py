"""Native context hook candidates; no shell execution or raw prompt retention."""
import json
from pathlib import Path
from . import runtime
from .cli import NaviError
from .agent_bridge import safe_target
from .skill_registry import read_json,write_private

def fragment(host):
    if host not in runtime.HOOKS:
        raise NaviError("Native context hook not implemented; use portable instructions")
    path,start,prompt=runtime.HOOKS[host]
    config={"hooks":{}}
    for event in (start,prompt):
        # Constant command, no interpolation of user paths, data or prompt.
        command="navi hook --host "+host+" --event "+event
        handler={"type":"command","command":command,"timeout":10 if host!="gemini" else 10000}
        config["hooks"][event]=[{"hooks":[handler]}]
    return path,config

def connection(root,store,host,mode="plan"):
    root=runtime._project(root);host=runtime._host(root,host)
    rel,config=fragment(host)
    target=safe_target(root,rel)
    directory,scope=runtime.nef._outside(root,store)
    if not directory.is_dir():raise NaviError("Create private receipt directory outside Git")
    receipt=safe_target(directory,"hook-"+scope+"-"+host+".json")
    raw=(json.dumps(config,indent=2)+"\n").encode("utf-8")
    import hashlib
    expected=hashlib.sha256(raw).hexdigest()
    # Receipt binds the exact generated bytes to this project and host.
    record={"schema_version":1,"scope":scope,"host":host,"path":rel,"sha256":expected}
    owner=receipt.is_file() and read_json(receipt)==record
    exists=target.exists()
    same=exists and target.is_file() and target.stat().st_size==len(raw) and target.read_bytes()==raw
    state="owned" if same and owner else ("conflict" if exists or receipt.exists() else "missing")
    out={"status":"planned","host":host,"path":rel,"state":state,"configuration":config,
         "scope":"Project-only candidate; no user/system settings, host launch or trust bypass. Review PATH and host configuration before enabling."}
    if mode=="plan":return out
    if mode=="check":return {**out,"status":"current" if state=="owned" else "review-required"}
    if mode=="disconnect":
        if state!="owned":return {**out,"status":"review-required"}
        # Recheck exact bytes immediately before removal. Requires trusted local tree/no concurrent edits.
        if safe_target(root,rel).read_bytes()!=raw:raise NaviError("Hook configuration changed")
        target.unlink()
        receipt.unlink()
        return {**out,"status":"disconnected"}
    if mode!="apply":raise NaviError("Invalid connection mode")
    if state=="owned":return {**out,"status":"current"}
    if state!="missing":return {**out,"status":"review-required"}
    # Refuse if another known NAVI-owned host configuration exists in this project.
    for other,(other_rel,*_) in runtime.HOOKS.items():
        if other!=host and safe_target(directory,"hook-"+scope+"-"+other+".json").exists():
            raise NaviError("Disconnect the other managed host first")
    target.parent.mkdir(parents=True,exist_ok=True)
    # Record intent first; interrupted writes are review-required, never automatically overwritten.
    write_private(receipt,record)
    with safe_target(root,rel).open("xb") as f:f.write(raw)
    return {**out,"status":"connected"}

def hook(host,event,payload):
    if host not in runtime.HOOKS or event not in runtime.HOOKS[host][1:]:
        raise NaviError("Unsupported hook event")
    if type(payload) is not dict or payload.get("hook_event_name")!=event:
        raise NaviError("Unexpected hook event payload")
    # Only fixed context; do not inspect, echo, hash, log or persist prompt/tool/transcript fields.
    text=("NAVI NEF: use only the selected agent. Read relevant project roadmap, handoff and manifest. "
          "For nontrivial work resolve material ambiguity with existing context first; ask the user if still unresolved. "
          "Use navi intake or managed runtime before implementation; never treat readiness as authorization. "
          "Verify actual results and update handoff. Propose only reviewed sanitized lessons; never save raw prompts.")
    if host=="gemini":return {"hookSpecificOutput":{"additionalContext":text}}
    return {"hookSpecificOutput":{"hookEventName":event,"additionalContext":text}}
